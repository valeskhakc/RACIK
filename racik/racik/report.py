def _rp(value: float, lang: str) -> str:
    sep = "." if lang == "id" else ","
    return "Rp" + f"{round(value):,}".replace(",", sep)


def _e(value) -> str:
    return html.escape(str(value if value is not None else ""))


def build_report(result: PlanResult, procurement: Iterable[ProcurementLine],
                 lang: str = "id", sppg_name: str = "") -> str:
    """Render the printable compliance + procurement document."""
    lang = norm_lang(lang)
    s = STRINGS[lang]
    slot_labels = SLOT_LABELS_ID if lang == "id" else SLOT_LABELS_EN
    label_idx = 0 if lang == "id" else 1
    request = result.request
    portions = request.portions
    lines = list(procurement)
    proc_totals = totals(lines)
    summary = result.summary()

    day_names = (["Senin", "Selasa", "Rabu", "Kamis", "Jumat", "Sabtu", "Minggu"]
                 if lang == "id" else
                 ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday",
                  "Saturday", "Sunday"])

    # ---------------------------------------------------------- menu table
    menu_rows = []
    for day in result.days:
        menu_rows.append(
            f'<tr class="day"><td colspan="5">{_e(day_names[day.day_index % 7])}'
            f' &mdash; {_rp(day.cost_per_portion_idr, lang)}/{"porsi" if lang=="id" else "portion"}'
            f' &middot; {day.nutrients["energy_kcal"]:.0f} {unit(lang, "kkal")}'
            f' &middot; AKG {result.adequacy(day) * 100:.0f}%</td></tr>')
        for slot in SLOTS:
            dish = day.dishes[slot]
            if dish is None:
                continue
            menu_rows.append(
                f"<tr><td>{_e(slot_labels[slot])}</td>"
                f"<td>{_e(dish.name)}</td><td>{_e(dish.province)}</td>"
                f'<td class="n">{dish.per_portion.get("energy_kcal", 0):.0f}</td>'
                f'<td class="n">{_rp(dish.cost_per_portion_idr, lang)}</td></tr>')

    # ---------------------------------------------------------- compliance
    compliance_rows = []
    for day in result.days:
        compliance_rows.append(
            f'<tr class="day"><td colspan="5">{_e(day_names[day.day_index % 7])}</td></tr>')
        for key, meta in NUTRIENT_META.items():
            target = result.targets.get(key)
            if not target:
                continue
            value = day.nutrients.get(key, 0.0)
            pct = value / target * 100
            binding = key in BINDING_NUTRIENTS
            cls = "" if pct >= 95 else "short" if pct >= 80 else "bad"
            tag = "" if binding else f' <span class="tag">{s["advisory"]}</span>'
            compliance_rows.append(
                f"<tr><td>{_e(meta[label_idx])}{tag}</td>"
                f'<td class="n">{value:.1f}</td>'
                f'<td class="n">{target:.1f} {_e(unit(lang, meta[2]))}</td>'
                f'<td class="n">{pct:.0f}%</td>'
                f'<td><div class="bar"><i class="{cls}" '
                f'style="width:{min(100, pct):.0f}%"></i></div></td></tr>')

    # ---------------------------------------------------------- relaxations
    if result.relaxations:
        relax_rows = "".join(
            f"<tr><td>{_e(day_names[r.day_index % 7])}</td>"
            f"<td>{_e(NUTRIENT_META[r.nutrient][label_idx])}</td>"
            f'<td class="n">{r.shortfall:.1f}</td>'
            f'<td class="n">{r.target:.1f} {_e(unit(lang, NUTRIENT_META[r.nutrient][2]))}</td>'
            f'<td class="n">-{r.share * 100:.0f}%</td></tr>'
            for r in result.relaxations)
        relax_block = (
            f'<div class="warn">{len(result.relaxations)} '
            f'{_e(s["relaxed"]).lower()}.</div>'
            f"<table><thead><tr><th>{_e(s['day'])}</th><th>{_e(s['nutrient'])}</th>"
            f"<th class='n'>{_e(s['short'])}</th><th class='n'>{_e(s['target'])}</th>"
            f"<th class='n'>{_e(s['pct'])}</th></tr></thead>"
            f"<tbody>{relax_rows}</tbody></table>")
    else:
        relax_block = f'<div class="note">{_e(s["relax_none"])}</div>'

    # ---------------------------------------------------------- procurement
    proc_rows = "".join(
        f"<tr><td>{_e(line.name)}</td>"
        f'<td class="n">{line.gross_kg:.2f} kg</td>'
        f'<td class="n">{_rp(line.cost_idr, lang)}</td>'
        f'<td style="font-size:8pt;color:#4A5A4C">'
        f'{_e(", ".join(sorted(line.used_in)[:2]))}</td></tr>'
        for line in lines)

    notes = "".join(f"<li>{_e(n)}</li>" for n in _notes_for(result, lang))
    region = request.province or s["none"]
    total_cost = result.mean_cost_per_portion * portions * len(result.days)

    return f"""<!DOCTYPE html>
<html lang="{lang}"><head><meta charset="utf-8">
<title>{_e(s['title'])} — Racik</title><style>{_CSS}</style></head>
<body><div class="sheet">

  <h1>{_e(s['title'])}</h1>
  <p class="sub">{_e(s['subtitle'])}{f" &middot; {_e(sppg_name)}" if sppg_name else ""}</p>

  <div class="meta">
    <div><b>{_e(s['generated'])}</b><span>{date.today().isoformat()}</span></div>
    <div><b>{_e(s['stage'])}</b><span>{_e(result.band.label_id if lang == 'id' else result.band.label_en)}</span></div>
    <div><b>{_e(s['days'])}</b><span>{len(result.days)}</span></div>
    <div><b>{_e(s['portions'])}</b><span>{portions:,}</span></div>
    <div><b>{_e(s['region'])}</b><span>{_e(region)}</span></div>
    <div><b>{_e(s['budget'])}</b><span>{_rp(request.config.ingredient_budget_idr, lang)}</span></div>
  </div>

  <h2>{_e(s['s_summary'])}</h2>
  <div class="kpis">
    <div class="kpi"><b>{_e(s['mean_cost'])}</b><span>{_rp(summary['mean_cost_per_portion_idr'], lang)}</span></div>
    <div class="kpi"><b>{_e(s['mean_adequacy'])}</b><span>{summary['mean_adequacy'] * 100:.0f}%</span></div>
    <div class="kpi"><b>{_e(s['total_cost'])}</b><span>{_rp(total_cost, lang)}</span></div>
    <div class="kpi"><b>{_e(s['relaxed'])}</b><span>{summary['relaxed_floors']}</span></div>
  </div>

  <h2>{_e(s['s_menu'])}</h2>
  <table><thead><tr><th>{_e(s['slot'])}</th><th>{_e(s['dish'])}</th>
    <th>{_e(s['province'])}</th><th class="n">{_e(s['energy'])}</th>
    <th class="n">{_e(s['cost'])}</th></tr></thead>
    <tbody>{''.join(menu_rows)}</tbody></table>

  <h2>{_e(s['s_compliance'])}</h2>
  <table><thead><tr><th>{_e(s['nutrient'])}</th><th class="n">{_e(s['value'])}</th>
    <th class="n">{_e(s['target'])}</th><th class="n">{_e(s['pct'])}</th>
    <th></th></tr></thead>
    <tbody>{''.join(compliance_rows)}</tbody></table>
  <div class="note">{_e(s['advisory_note'])}</div>

  <h2>{_e(s['s_relax'])}</h2>
  {relax_block}

  <h2>{_e(s['s_proc'])}</h2>
  <p class="sub">{proc_totals['items']} {_e(s['items'])} &middot;
     {proc_totals['total_mass_kg']:,.1f} kg &middot;
     {_rp(proc_totals['total_cost_idr'], lang)}</p>
  <table><thead><tr><th>{_e(s['ingredient'])}</th>
    <th class="n">{_e(s['weight'])}</th><th class="n">{_e(s['cost'])}</th>
    <th>{_e(s['used_in'])}</th></tr></thead>
    <tbody>{proc_rows}</tbody></table>

  <h2>{_e(s['s_notes'])}</h2>
  <ul>{notes}</ul>

  <div class="sign">
    <div>{_e(s['sign_prepared'])}</div>
    <div>{_e(s['sign_approved'])}</div>
  </div>

  <p class="foot">{_e(s['footer'])}</p>
</div></body></html>"""


def plan_notes(result: PlanResult, lang: str = "id") -> list[str]:
    """Methodology caveats attached to every plan and to this report.

    Lives here rather than in api.py so the report and the API cannot drift
    into telling a reader two different stories about the same numbers.
    """
    label = 0 if norm_lang(lang) == "id" else 1
    notes = [t(lang, "note.compliance_method",
               fraction=f"{MBG.akg_fraction * 100:.0f}%"),
             t(lang, "note.method"), t(lang, "note.servings"),
             t(lang, "note.prices")]
    if not result.request.enforce_micronutrients:
        notes.append(t(lang, "note.micro"))
    if result.budget_overrun_idr > 0:
        notes.append(t(lang, "note.overrun",
                       amount=f"{result.budget_overrun_idr:,.0f}"))
    if result.relaxations:
        worst = result.relaxations[0]
        notes.append(t(lang, "note.relaxed", count=len(result.relaxations),
                       nutrient=NUTRIENT_META[worst.nutrient][label],
                       day=worst.day_index + 1, share=f"{worst.share:.0%}"))
    return notes


def _notes_for(result: PlanResult, lang: str) -> list[str]:
    return plan_notes(result, lang)
