"""The compliance and procurement report.

Everything else in Racik is a screen. This is the document: one printable page
an SPPG hands to a supervisor, an auditor, or the BGN — showing what will be
served, whether it meets AKG, what it costs, and what to buy.

It is deliberately a single self-contained HTML file with print styles rather
than a generated PDF: no extra dependency, it prints to PDF from any browser,
and it stays readable if someone opens the file in five years.

The report states its own limits. A compliance document that hides a relaxed
nutrient floor, or presents an unverified micronutrient as if it were enforced,
is worse than no document — so relaxations get their own section and advisory
nutrients are marked in every table they appear in.
"""
